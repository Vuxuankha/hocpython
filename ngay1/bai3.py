ban_kinh_hinh_tron = float(input("Nhập bán kính hình tròn: "))
dien_tich = 3.14 * ban_kinh_hinh_tron ** 2
print(f"Diện tích hình tròn có bán kính {ban_kinh_hinh_tron} là: {dien_tich:.2f}")
chu_vi = 2 * 3.14 * ban_kinh_hinh_tron
print(f"Chu vi hình tròn có bán kính {ban_kinh_hinh_tron} là: {chu_vi:.2f}")